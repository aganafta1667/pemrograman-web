const searchType = document.getElementById("searchType");
const sectionWilayah = document.getElementById("sectionWilayah");
const sectionKodePos = document.getElementById("sectionKodePos");
const provinceSelect = document.getElementById("province");
const citySelect = document.getElementById("city");
const districtSelect = document.getElementById("district");
const postalCodeInput = document.getElementById("postalCodeInput");
const searchForm = document.getElementById("searchForm");
const submitBtn = document.getElementById("submitBtn");
const resultSummary = document.getElementById("resultSummary");
const results = document.getElementById("results");

function isiPilihan(select, placeholder, values) {
  select.innerHTML = `<option value="">${placeholder}</option>`;
  values.forEach((value) => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.appendChild(option);
  });
}

function nilaiUnik(items) {
  return [...new Set(items)].sort((a, b) => a.localeCompare(b, "id"));
}

isiPilihan(provinceSelect, "Pilih provinsi", nilaiUnik(dataKodePos.map(item => item.provinsi)));

searchType.addEventListener("change", function () {
  const mode = searchType.value;
  if (mode === "wilayah") {
    sectionWilayah.style.display = "block";
    sectionKodePos.style.display = "none";
    submitBtn.innerHTML = `<span aria-hidden="true">⌕</span> Cari Kode Pos`;
  } else {
    sectionWilayah.style.display = "none";
    sectionKodePos.style.display = "block";
    submitBtn.innerHTML = `<span aria-hidden="true">⌕</span> Cari Wilayah`;
  }
  resetHasil();
});

provinceSelect.addEventListener("change", function () {
  const provinsi = provinceSelect.value;
  const kota = nilaiUnik(dataKodePos.filter(item => item.provinsi === provinsi).map(item => item.kota));
  isiPilihan(citySelect, "Pilih kabupaten/kota", kota);
  citySelect.disabled = !provinsi;
  isiPilihan(districtSelect, "Pilih kecamatan", []);
  districtSelect.disabled = true;
  resetHasil();
});

citySelect.addEventListener("change", function () {
  const provinsi = provinceSelect.value;
  const kota = citySelect.value;
  const kecamatan = nilaiUnik(dataKodePos
    .filter(item => item.provinsi === provinsi && item.kota === kota)
    .map(item => item.kecamatan));
  isiPilihan(districtSelect, "Pilih kecamatan", kecamatan);
  districtSelect.disabled = !kota;
  resetHasil();
});

districtSelect.addEventListener("change", resetHasil);
postalCodeInput.addEventListener("input", function () {
  this.value = this.value.replace(/\D/g, "");
});

function resetHasil() {
  if (searchType.value === "wilayah") {
    resultSummary.textContent = "Klik tombol Cari Kode Pos untuk menampilkan hasil wilayah yang dipilih.";
  } else {
    resultSummary.textContent = "Masukkan kode pos lalu klik tombol Cari Wilayah.";
  }
  results.innerHTML = `<div class="empty-state"><div class="empty-icon">⌖</div><p>Hasil pencarian akan ditampilkan di sini.</p></div>`;
}

function renderHasil(hasil, isKodePosSearch = false) {
  if (hasil.length === 0) {
    results.innerHTML = `<div class="empty-state"><div class="empty-icon">⌕</div><p>Data tidak ditemukan.</p></div>`;
    return;
  }

  results.innerHTML = "";
  hasil.forEach(item => {
    const card = document.createElement("article");
    card.className = "result-card";
    const headerTitle = isKodePosSearch 
      ? `Kode Pos: ${item.kodePos}` 
      : item.kecamatan;

    card.innerHTML = `
      <div class="card-title">${headerTitle}</div>
      <div class="card-body">
        <div class="postal-code">${item.kodePos}</div>
        <div class="location-line"><strong>Kelurahan:</strong> ${item.kelurahan}</div>
        <div class="location-line"><strong>Kecamatan:</strong> ${item.kecamatan}</div>
        <div class="location-line"><strong>Kota/Kabupaten:</strong> ${item.kota}</div>
        <div class="location-line"><strong>Provinsi:</strong> ${item.provinsi}</div>
      </div>`;
    results.appendChild(card);
  });
}

searchForm.addEventListener("submit", function (event) {
  event.preventDefault();

  const mode = searchType.value;

  if (mode === "wilayah") {
    const provinsi = provinceSelect.value;
    const kota = citySelect.value;
    const kecamatan = districtSelect.value;

    if (!provinsi || !kota || !kecamatan) {
      resultSummary.textContent = "Silakan pilih provinsi, kabupaten/kota, dan kecamatan terlebih dahulu.";
      return;
    }

    const hasil = dataKodePos.filter(item =>
      item.provinsi === provinsi &&
      item.kota === kota &&
      item.kecamatan === kecamatan
    );

    resultSummary.textContent = `Ditemukan ${hasil.length} data kode pos untuk Kecamatan ${kecamatan}, Kota ${kota}, Provinsi ${provinsi}.`;
    renderHasil(hasil, false);
  } else {
    const inputKodePos = postalCodeInput.value.trim();

    if (!inputKodePos) {
      resultSummary.textContent = "Silakan masukkan kode pos terlebih dahulu.";
      return;
    }

    const hasil = dataKodePos.filter(item => item.kodePos.includes(inputKodePos));

    resultSummary.textContent = `Hasil pencarian kode pos dengan menggunakan kata kunci "${inputKodePos}" telah ditemukan sebnyak ${hasil.length} buah.`;
    renderHasil(hasil, true);
  }
});
